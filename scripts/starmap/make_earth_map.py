"""Earth's surface for the star map (web/data/earth.js): NASA's Blue Marble, shrunk to a pixel-art map.

    .venv\\Scripts\\python scripts\\starmap\\make_earth_map.py

Source: NASA Visible Earth, "Blue Marble: Land Surface, Shallow Water, and Shaded Topography"
(NASA Goddard / MODIS, public domain). The 2048 x 1024 map is averaged down to 128 x 64 pixels
(about 2.8 degrees each), and every pixel is given the nearest of a few surface types (ocean, shallow
water, forest, grassland, desert, dry land, rock, ice). The page wraps this map onto a turning globe,
so the continents are the real ones. Run once; the output is committed.
"""

import io
import json
import urllib.request
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'web' / 'data' / 'earth.js'
SOURCE = 'https://eoimages.gsfc.nasa.gov/images/imagerecords/57000/57752/land_shallow_topo_2048.jpg'
CREDIT = 'NASA Visible Earth: Blue Marble (land surface, shallow water and shaded topography), public domain'
W, H = 128, 64

# Surface types: (code, how it looks in the Blue Marble image, colour on the site).
TYPES = [
    ('o', [(13, 26, 66), (20, 37, 85)], '#2a5fbf'),          # ocean
    ('s', [(36, 76, 126), (60, 110, 150)], '#3f86d8'),        # shallow water
    ('f', [(28, 56, 26), (44, 72, 34)], '#3d7a35'),           # forest
    ('g', [(84, 98, 52), (110, 116, 70)], '#6f9a48'),         # grassland
    ('d', [(206, 176, 128), (180, 150, 105)], '#d1b07a'),     # desert
    ('b', [(140, 112, 76), (118, 98, 72)], '#9a7a50'),        # dry land
    ('r', [(96, 92, 86), (150, 142, 132)], '#8d877d'),        # rock, tundra
    ('i', [(232, 236, 240), (205, 212, 220)], '#eef6ff'),     # ice and snow
]


def classify(rgb):
    anchors = [(code, np.array(c, float)) for code, cols, _ in TYPES for c in cols]
    flat = rgb.reshape(-1, 3).astype(float)
    dist = np.stack([((flat - a) ** 2).sum(1) for _, a in anchors], 1)
    codes = np.array([code for code, _ in anchors])[dist.argmin(1)]
    return codes.reshape(rgb.shape[:2])


def polar_rules(codes):
    """Colour alone mixes up bright desert and ice; latitude settles it."""
    lat = 90 - (np.arange(H) + 0.5) * 180 / H
    for y, row in enumerate(codes):
        land = ~np.isin(row, ['o', 's'])
        if abs(lat[y]) < 55:
            row[row == 'i'] = 'd'                      # bright land near the equator is desert (Sahara)
        if lat[y] < -62:
            row[land] = 'i'                            # Antarctica: an ice sheet
        if lat[y] > 81:
            row[:] = 'i'                               # the Arctic ice pack, there all year
        if lat[y] > 66:
            row[land & np.isin(row, ['r', 'd'])] = 'i'   # Greenland and Arctic islands
    return codes


def main():
    with urllib.request.urlopen(SOURCE, timeout=60) as r:
        img = Image.open(io.BytesIO(r.read())).convert('RGB')
    small = np.asarray(img.resize((W, H), Image.BOX))
    codes = polar_rules(classify(small))
    rows = [''.join(row) for row in codes]
    data = {'source': SOURCE, 'credit': CREDIT, 'width': W, 'height': H,
            'colors': {code: color for code, _, color in TYPES}, 'rows': rows}
    OUT.write_text('// Generated by scripts/starmap/make_earth_map.py. Do not edit by hand.\n'
                   f'window.STARMAP_EARTH = {json.dumps(data, separators=(",", ":"))};\n', encoding='utf-8')
    land = sum(ch not in 'os' for row in rows for ch in row) / (W * H)
    print(f'Saved {OUT.relative_to(ROOT)}: {W}x{H}, land {land:.0%} (Earth: ~29%)')
    for row in rows[::4]:
        print(row)


if __name__ == '__main__':
    main()
