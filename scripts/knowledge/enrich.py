"""Compute a world's generated knowledge fields from the map's own data (docs/plans/KNOWLEDGE_AND_RESEARCHERS.md 11).

    .venv\\Scripts\\python scripts\\knowledge\\enrich.py "Kepler-22 b"            # print the generated block
    .venv\\Scripts\\python scripts\\knowledge\\enrich.py "Kepler-22 b" --write    # create/refresh knowledge/worlds/

Only what a script can compute from the exported catalogue (web/data/details/, NASA's values): the size class
(Kepler's own size bins), starlight and year length relative to Earth, the temperature, whether the orbit lies
in the map's habitable zone, the discovery year, the most similar known worlds and how unusual its size is for
its starlight. Nothing is written here that needs a source beyond NASA's archive: the stories, facts and notes in
a world's file are written by people and reviewed by pull request (knowledge/README.md). --write replaces only the
generated block between the GENERATED markers, so reviewed text is never touched.
"""

import argparse
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DETAILS = ROOT / 'web' / 'data' / 'details'
WORLDS = ROOT / 'knowledge' / 'worlds'
TEMPLATE = WORLDS / 'TEMPLATE.md'
START = '<!-- GENERATED by scripts/knowledge/enrich.py from NASA data: do not edit by hand -->'
END = '<!-- END GENERATED -->'
# Kepler's size classes (Batalha et al. 2013, ApJS 204, 24), in Earth radii.
SIZE_CLASSES = [(1.25, 'Earth-size'), (2.0, 'super-Earth'), (6.0, 'Neptune-size'), (15.0, 'Jupiter-size'),
                (math.inf, 'larger than Jupiter')]


def load_systems(folder: Path = DETAILS) -> dict:
    """{system name: detail} from the map's detail chunks (JavaScript wrapping JSON)."""
    systems: dict = {}
    for f in sorted(folder.glob('*.js')):
        text = f.read_text(encoding='utf-8')
        start, end = text.index(',', text.index('STARMAP_DETAILS(')) + 1, text.rindex(')')
        systems.update(json.loads(text[start:end]))
    return systems


def habitable_zone(detail: dict) -> tuple[float, float] | None:
    """(inner, outer) AU: the map's own approximation (export_starmap.py), 1.1 and 0.36 x Earth's sunlight."""
    if detail.get('teff') is None or detail.get('srad') is None:
        return None
    lum = detail['srad'] ** 2 * (detail['teff'] / 5772) ** 4
    return (lum / 1.1) ** 0.5, (lum / 0.36) ** 0.5


def size_class(radius: float) -> str:
    return next(name for top, name in SIZE_CLASSES if radius < top)


def worlds(systems: dict) -> list[dict]:
    """Every confirmed planet with its system's star, flattened."""
    out = []
    for name, d in systems.items():
        for p in d.get('planets', []):
            if p.get('status') == 'confirmed':
                out.append({**p, 'system': name, 'hz': habitable_zone(d)})
    return out


def _key(p: dict) -> tuple[float, float, float] | None:
    if not all(isinstance(p.get(k), (int, float)) and p[k] > 0 for k in ('radius', 'insol', 'period')):
        return None
    return math.log10(p['radius']), math.log10(p['insol']), math.log10(p['period'])


def similar(world: dict, others: list[dict], n: int = 5) -> list[dict]:
    """The n confirmed worlds nearest in size, starlight and year length (equal weights, on log scales)."""
    k = _key(world)
    if k is None:
        return []
    scored = []
    for o in others:
        ko = _key(o)
        if ko is not None and o['name'] != world['name']:
            scored.append((math.dist(k, ko), o['name'], o))
    return [o for _, _, o in sorted(scored)[:n]]


def size_for_starlight(world: dict, others: list[dict]) -> tuple[int, int] | None:
    """(how many of the worlds getting similar starlight, within a factor of 2, are smaller; how many there are)."""
    if not world.get('radius') or not world.get('insol'):
        return None
    peers = [o for o in others if o.get('radius') and o.get('insol') and o['name'] != world['name']
             and 0.5 <= o['insol'] / world['insol'] <= 2]
    return (sum(o['radius'] < world['radius'] for o in peers), len(peers)) if peers else None


def generated_block(world: dict, others: list[dict]) -> str:
    """The generated section of a world's file, as Markdown."""
    rows = []
    if world.get('radius'):
        rows.append(('Size', f"{world['radius']:g} x Earth's radius: {size_class(world['radius'])} (Kepler's size classes)"))
    if world.get('insol') is not None:
        rows.append(('Starlight', f"{world['insol']:g} x what Earth gets from the Sun"))
    if world.get('teq') is not None:
        rows.append(('Temperature', (f"about {world['teq']:.0f} K ({world['teq'] - 273.15:.0f} °C) if it were a bare rock "
                                    '(the equilibrium temperature; no atmosphere counted)')))
    if world.get('period'):
        rows.append(('Year', f"{world['period']:g} days ({world['period'] / 365.25:.2f} Earth years)"))
    hz, sma = world.get('hz'), world.get('sma')
    if hz and sma:
        inside = hz[0] <= sma <= hz[1]
        rows.append(('Habitable zone', ('the orbit is inside the map\'s habitable zone' if inside else
                                        'the orbit is outside the map\'s habitable zone')
                     + f' ({hz[0]:.2f} to {hz[1]:.2f} AU). An orbit there does not make a world habitable.'))
    if world.get('year'):
        rows.append(('Discovered', str(world['year'])))
    rank = size_for_starlight(world, others)
    if rank:
        smaller, total = rank
        rows.append(('For its starlight', (f'larger than {round(100 * smaller / total)}% of the {total} confirmed worlds '
                                          'that get within a factor of 2 of the same starlight')))
    near = similar(world, others)
    lines = [START, '', '| Computed | Value |', '|---|---|']
    lines += [f'| {k} | {v} |' for k, v in rows]
    if near:
        lines += ['', "**Most similar known worlds** (size, starlight and year length; Colossus's comparison):", '']
        lines += [f"- {o['name']} ({o['radius']:g} x Earth, {o['insol']:g} x Earth's starlight, {o['period']:g} days)"
                  for o in near]
    lines += ['', f"Source: NASA Exoplanet Archive values as exported to the map (system {world['system']}).", '', END]
    return '\n'.join(lines)


def slug(name: str) -> str:
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def write_world(world: dict, others: list[dict], folder: Path = WORLDS, template: Path = TEMPLATE) -> Path:
    """Create the world's file from the template, or refresh only its generated block."""
    path = folder / f"{slug(world['name'])}.md"
    text = path.read_text(encoding='utf-8') if path.exists() else template.read_text(encoding='utf-8').replace(
        '{{name}}', world['name']).replace('{{system}}', world['system'])
    if text.count(START) != 1 or text.count(END) != 1:
        sys.exit(f'{path.name}: expected one generated block ({START} ... {END}).')
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    path.write_text(head + generated_block(world, others) + tail, encoding='utf-8', newline='\n')
    return path


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('world', help='a confirmed planet\'s name as the map shows it, e.g. "Kepler-22 b"')
    parser.add_argument('--write', action='store_true', help='create or refresh knowledge/worlds/<world>.md')
    args = parser.parse_args(argv)
    every = worlds(load_systems())
    match = [w for w in every if w['name'].lower() == args.world.lower()]
    if not match:
        sys.exit(f'No confirmed world named {args.world!r} in the map\'s data.')
    if args.write:
        print(f'Wrote {write_world(match[0], every).relative_to(ROOT)}')
    else:
        print(generated_block(match[0], every))


if __name__ == '__main__':
    main()
