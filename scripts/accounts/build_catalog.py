"""Keep the database's catalog of achievements and easter eggs in step with the game's code.

    .venv\\Scripts\\python scripts\\accounts\\build_catalog.py           # writes a migration for any new ids
    .venv\\Scripts\\python scripts\\accounts\\build_catalog.py --check   # exits 1 if the code and the catalog differ

The code is the master list (`ACHIEVEMENTS` and `EGGS` in web/src/48-gallery.js). The catalog is the sum of the
generated migrations in supabase/migrations/ (each starts with GENERATED below). Ids are only ever added: one that
is in the catalog but gone from the code is an error, since saved progress refers to it (`SHIPPED_IDS`).
After writing a migration, apply it with `npx supabase@2.122.1 migration up` (it keeps the accounts).
"""

import argparse
import re
import sys
from datetime import date, datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GALLERY = ROOT / 'web' / 'src' / '48-gallery.js'
MIGRATIONS = ROOT / 'supabase' / 'migrations'
GENERATED = '-- Generated by scripts/accounts/build_catalog.py from web/src/48-gallery.js: do not edit.'
ROW = re.compile(r"\('(ach|egg)', '([\w-]+)', '\d{4}-\d{2}-\d{2}'\)")


def code_ids() -> set[tuple[str, str]]:
    """(kind, id) for every achievement and easter egg in the game's code."""
    js = GALLERY.read_text(encoding='utf-8')
    eggs = js[js.index('const EGGS = ['):js.index('const EGG = new Map')]
    ach = js[js.index('const ACHIEVEMENTS = ['):js.index('const ACH = new Map')]
    ids = re.compile(r"\bid: '([\w-]+)'")
    return {('egg', i) for i in ids.findall(eggs)} | {('ach', i) for i in ids.findall(ach)}


def catalog_ids() -> set[tuple[str, str]]:
    """(kind, id) for every row the generated migrations add."""
    rows: set[tuple[str, str]] = set()
    for f in sorted(MIGRATIONS.glob('*.sql')):
        text = f.read_text(encoding='utf-8')
        if text.startswith(GENERATED):
            rows |= set(ROW.findall(text))
    return rows


def migration_sql(rows: set[tuple[str, str]], today: date) -> str:
    values = ',\n'.join(f"  ('{k}', '{i}', '{today.isoformat()}')" for k, i in sorted(rows))
    return f"""{GENERATED}
-- {len(rows)} new id(s) for public.catalog (20261128000000_catalog.sql).
insert into public.catalog (kind, item_id, added_on) values
{values}
on conflict do nothing;
"""


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='only check; exit 1 if anything differs')
    parser.add_argument('--stamp', help='the migration timestamp (default: now, UTC)')
    args = parser.parse_args(argv)

    code, catalog = code_ids(), catalog_ids()
    gone, new = catalog - code, code - catalog
    if gone:
        sys.exit('In the catalog but gone from the code (ids are never removed): '
                 + ', '.join(f'{k}:{i}' for k, i in sorted(gone)))
    if not new:
        print(f'The catalog matches the code ({len(code)} ids).')
        return
    if args.check:
        sys.exit(f'{len(new)} id(s) missing from the catalog: run scripts/accounts/build_catalog.py. '
                 + ', '.join(f'{k}:{i}' for k, i in sorted(new)))
    stamp = args.stamp or datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')
    latest = max((f.name.split('_', 1)[0] for f in MIGRATIONS.glob('*.sql')), default='0')
    if not re.fullmatch(r'\d{14}', stamp) or stamp <= latest:
        sys.exit(f'The timestamp must be 14 digits and later than the last migration ({latest}).')
    out = MIGRATIONS / f'{stamp}_catalog_ids.sql'
    out.write_text(migration_sql(new, date.today()), encoding='utf-8', newline='\n')
    print(f'Wrote {out.relative_to(ROOT)} with {len(new)} id(s). Apply it: npx supabase@2.122.1 migration up')


if __name__ == '__main__':
    main()
