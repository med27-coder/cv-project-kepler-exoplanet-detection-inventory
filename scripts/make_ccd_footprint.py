"""Kepler's 21 CCD modules on the sky, for the star map (web/data/ccd.js).

    .venv\\Scripts\\python scripts\\make_ccd_footprint.py      # needs: pip install -r requirements-dev.txt

Uses the K2fov package (MIT; Kepler/K2 Guest Observer Office), where the original Kepler field is
"campaign 1000". Each module's outline is the convex hull of its four output channels' corners.
The corner fine-guidance sensors are left out. The outlines were checked against the KOI stars,
which cluster on the modules. Run once; the output is committed.
"""

import json
import logging
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'web' / 'data' / 'ccd.js'
FGS_MODULES = {1, 5, 21, 25}   # corner positions: fine guidance sensors, not science CCDs


def module_outlines():
    logging.disable(logging.WARNING)   # K2fov warns that field 1000's pointing is "preliminary"
    from K2fov import fields
    from scipy.spatial import ConvexHull
    corners = fields.getKeplerFov(1000).getCoordsOfChannelCorners()   # module, output, channel, ra, dec
    out = []
    for module in sorted(set(corners[:, 0].astype(int)) - FGS_MODULES):
        pts = corners[corners[:, 0] == module][:, 3:5]
        hull = pts[ConvexHull(pts).vertices]
        out.append(np.round(hull, 3).tolist())
    return out


def main():
    outlines = module_outlines()
    OUT.write_text('// Generated by scripts/make_ccd_footprint.py (K2fov, Kepler field). Do not edit.\n'
                   f'window.STARMAP_CCD = {json.dumps(outlines, separators=(",", ":"))};\n', encoding='utf-8')
    print(f'Saved {OUT.relative_to(ROOT)}: {len(outlines)} modules')


if __name__ == '__main__':
    main()
