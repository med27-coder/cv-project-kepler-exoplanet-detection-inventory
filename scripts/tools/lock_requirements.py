"""Regenerate the hash-locked dependency files from requirements.txt / requirements-dev.txt.

    .venv\\Scripts\\python -m pip install uv
    .venv\\Scripts\\python scripts\\tools\\lock_requirements.py

requirements.lock (app) and requirements-dev.lock (app + test tools, used by CI) pin every package,
including indirect ones, to an exact version with its SHA-256 hashes for all platforms (uv's
universal resolution, Python 3.12). Installing with `pip install --require-hashes -r <lock>` then
refuses any file that doesn't match, so a compromised or swapped upload on PyPI can't sneak in.
The project's own package (-e .) has no hash; install it afterwards with `pip install --no-deps -e .`.
Re-run after changing requirements*.txt (Dependabot security PRs update the .txt files).
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ('# Generated by scripts/tools/lock_requirements.py from {src}. Do not edit by hand.\n'
          '# Install: pip install --require-hashes -r {out} && pip install --no-deps -e .\n')


def requirements(path, seen=None):
    """Lines of a requirements file with -r includes expanded and -e lines dropped."""
    seen = seen or set()
    out = []
    for line in path.read_text(encoding='utf-8').splitlines():
        line = line.split('#')[0].strip()
        if not line or line.startswith('-e '):
            continue
        if line.startswith('-r '):
            inc = path.parent / line[3:].strip()
            if inc not in seen:
                seen.add(inc)
                out += requirements(inc, seen)
            continue
        out.append(line)
    return out


def lock(src, out):
    with tempfile.TemporaryDirectory() as tmp:
        spec = Path(tmp) / 'requirements.in'
        spec.write_text('\n'.join(requirements(ROOT / src)) + '\n', encoding='utf-8')
        target = Path(tmp) / 'out.txt'
        subprocess.run([sys.executable, '-m', 'uv', 'pip', 'compile', str(spec), '--universal',
                        '--python-version', '3.12', '--generate-hashes', '--no-header', '-q',
                        '-o', str(target)], check=True)
        body = target.read_text(encoding='utf-8').replace(str(spec), src)
    (ROOT / out).write_text(HEADER.format(src=src, out=out) + body, encoding='utf-8')
    print(f'{out}: {sum(1 for ln in body.splitlines() if ln and ln[0].isalnum())} packages')


def main():
    lock('requirements.txt', 'requirements.lock')
    lock('requirements-dev.txt', 'requirements-dev.lock')


if __name__ == '__main__':
    main()
